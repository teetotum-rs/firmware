//! What an access point with an IP stack and one HTTP socket costs the internal heap, next to BLE.
//!
//! Sharing the SD card over Wi-Fi either fits beside everything the firmware already runs or
//! has to be a mode of its own. This run answers that by building the pieces one at a time on
//! the same two heap regions the firmware has, and logging the heap after each:
//!
//! 1. the empty heap, to set against the firmware's free heap at boot
//! 2. the Wi-Fi controller and the BLE host, as the firmware brings them up (coex included)
//! 3. the access point started: WPA2, SSID and a random password in the log
//! 4. `embassy-net` on the access point interface, static `192.168.4.1/24`, [`SOCKETS`] sockets
//! 5. a DHCP server (`edge-dhcp`) on a UDP socket with its buffers on the heap
//! 6. one TCP socket on port 80, its buffers on the heap or in external RAM ([`BUFFERS_IN_PSRAM`])
//! 7. a client joined, then the peak over [`WATCH`] while it is served
//!
//! `GET /` answers a fixed page, `GET /blob` sends [`BLOB`] generated bytes, so a download
//! measures the network and not the card.
//!
//! No screen, no hand:
//!
//! ```text
//! cargo build --release --bin apheap
//! espflash flash --chip esp32s3 -B 921600 --partition-table partitions.csv --erase-parts otadata target/xtensa-esp32s3-none-elf/release/apheap
//! tools/listen.py --seconds 180
//! ```

