/// Sockets the stack reserves room for. The plan measures 3 and 6, one build each.
const SOCKETS: usize = 6;

/// Whether the TCP buffers live in external RAM instead of the heap.
const BUFFERS_IN_PSRAM: bool = true;

/// TCP receive and transmit buffer, each.
const TCP_BUFFER: usize = 8192;

/// Bytes `GET /blob` hands the socket per write, fixed so a buffer change is the only change.
const CHUNK: usize = 1536;

/// The access point's own address, and the DHCP server's.
const SERVER_IP: Ipv4Addr = Ipv4Addr::new(192, 168, 4, 1);

/// DHCP socket buffer, each way. A DHCP message is at most a few hundred bytes.
const DHCP_BUFFER: usize = 1024;

/// Leases the DHCP server keeps.
const LEASES: usize = 4;

/// Bytes `GET /blob` sends.
const BLOB: usize = 1024 * 1024;

/// How long the heap is watched once a client has joined.
const WATCH: Duration = Duration::from_secs(30);

/// How often the heap is logged while the run waits or watches.
const TICK: Duration = Duration::from_secs(5);

const PAGE: &str = "<!doctype html><title>apheap</title><p>TeeToTum access point</p>";

/// Logs the heap after a stage, with the change since the previous one.
fn stage(name: &str, last: &mut usize) {
    let used = esp_alloc::HEAP.used();
    info!(
        "apheap: {name}: free {} used {} ({:+}) peak {}",
        esp_alloc::HEAP.free(),
        used,
        used as isize - *last as isize,
        esp_alloc::HEAP.stats().max_usage
    );
    *last = used;
}

#[esp_rtos::main]
async fn main(_spawner: Spawner) -> ! {
    esp_println::logger::init_logger_from_env();
    let peripherals = esp_hal::init(esp_hal::Config::default().with_cpu_clock(CpuClock::max()));

    // The same two regions the firmware has.
    esp_alloc::heap_allocator!(#[esp_hal::ram(reclaimed)] size: 73744);
    esp_alloc::heap_allocator!(size: 64 * 1024);

    // Brought up in both settings of `BUFFERS_IN_PSRAM`, so the setting is the only difference.
    let psram = Psram::new(
        peripherals.PSRAM,
        PsramConfig {
            mode: PsramMode::OctalSpi,
            ..Default::default()
        },
    );

    info!("--- apheap: sockets {SOCKETS}, tcp buffers {TCP_BUFFER}, in psram {BUFFERS_IN_PSRAM} ---");
    let mut last = esp_alloc::HEAP.used();
    stage("1 empty heap", &mut last);

    let timg0 = TimerGroup::new(peripherals.TIMG0);
    let sw_interrupt =
        esp_hal::interrupt::software::SoftwareInterruptControl::new(peripherals.SW_INTERRUPT);
    esp_rtos::start(timg0.timer0, sw_interrupt.software_interrupt0);
    stage("1b scheduler", &mut last);

    let (mut wifi, interfaces) = esp_radio::wifi::new(peripherals.WIFI, Default::default())
        .expect("Wi-Fi controller");
    stage("2a wifi controller", &mut last);

    let transport = BleConnector::new(peripherals.BT, Default::default()).expect("BLE connector");
    let ble_controller = ExternalController::<_, 1>::new(transport);
    let mut ble_resources: HostResources<DefaultPacketPool, 1, 1> = HostResources::new();
    let ble = trouble_host::new(ble_controller, &mut ble_resources);
    let Host { mut runner, .. } = ble.build();
    stage("2b ble host", &mut last);

    let rng = esp_hal::rng::Rng::new();
    let mac = interfaces.access_point.mac_address();
    let ssid = format!("TeeToTum-{:02X}{:02X}", mac[4], mac[5]);
    let password: String = (0..6)
        .map(|_| format!("{:04x}", rng.random() & 0xFFFF))
        .collect();
    let ap = AccessPointConfig::default()
        .with_ssid(ssid.as_str())
        .with_auth_method(AuthenticationMethod::Wpa2Personal)
        .with_password(password.clone())
        .with_max_connections(4);
    if let Err(err) = wifi.set_config(&WifiConfig::AccessPoint(ap)) {
        error!("apheap: access point refused: {err:?}");
        teetotum::step::halt()
    }
    info!("apheap: ssid {ssid} password {password}");
    stage("3 access point", &mut last);

    static RESOURCES: StaticCell<StackResources<SOCKETS>> = StaticCell::new();
    let config = embassy_net::Config::ipv4_static(StaticConfigV4 {
        address: Ipv4Cidr::new(Ipv4Address::new(192, 168, 4, 1), 24),
        gateway: None,
        dns_servers: Default::default(),
    });
    let seed = (u64::from(rng.random()) << 32) | u64::from(rng.random());
    let (stack, mut net) = embassy_net::new(
        interfaces.access_point,
        config,
        RESOURCES.init(StackResources::new()),
        seed,
    );
    stage("4 ip stack", &mut last);

    let mut dhcp = UdpSocket::new(
        stack,
        Box::leak(Box::new([PacketMetadata::EMPTY; 2])),
        vec![0u8; DHCP_BUFFER].leak(),
        Box::leak(Box::new([PacketMetadata::EMPTY; 2])),
        vec![0u8; DHCP_BUFFER].leak(),
    );
    if let Err(err) = dhcp.bind(67) {
        error!("apheap: dhcp bind: {err:?}");
        teetotum::step::halt()
    }
    let mut leases = DhcpServer::<fn() -> u64, LEASES>::new(now_secs, SERVER_IP);
    stage("5 dhcp server", &mut last);

    // Only the CPU copies to and from these: the driver builds each frame in its own memory.
    let (rx, tx): (&'static mut [u8], &'static mut [u8]) = if BUFFERS_IN_PSRAM {
        let (start, _) = psram.raw_parts();
        // SAFETY: the external RAM is mapped for as long as `psram` lives, which is to the end
        // of `main`, and nothing else is handed any of it.
        let both = unsafe { core::slice::from_raw_parts_mut(start, 2 * TCP_BUFFER) };
        both.split_at_mut(TCP_BUFFER)
    } else {
        (vec![0u8; TCP_BUFFER].leak(), vec![0u8; TCP_BUFFER].leak())
    };
    let mut socket = TcpSocket::new(stack, rx, tx);
    socket.set_timeout(Some(Duration::from_secs(10)));
    stage("6 tcp socket", &mut last);

    let serving = async {
        loop {
            if let Err(err) = socket.accept(80).await {
                error!("apheap: accept: {err:?}");
                continue;
            }
            let path = request_path(&mut socket).await;
            let began = Instant::now();
            let sent = match path {
                Some(Path::Root) => respond(&mut socket, "text/html", PAGE.as_bytes(), 0).await,
                Some(Path::Blob) => respond(&mut socket, "application/octet-stream", &[], BLOB).await,
                None => respond(&mut socket, "text/plain", b"not found", 0).await,
            };
            let ms = began.elapsed().as_millis().max(1);
            info!(
                "apheap: served {sent} bytes in {ms} ms ({} KiB/s), peak {}",
                sent as u64 * 1000 / 1024 / ms,
                esp_alloc::HEAP.stats().max_usage
            );
            socket.close();
            let _ = socket.flush().await;
            socket.abort();
        }
    };

    let dhcp_serving = async {
        // No gateway: the knob must never become a client's route anywhere.
        let options = ServerOptions::new(SERVER_IP, None);
        let mut incoming = [0u8; DHCP_BUFFER];
        let mut outgoing = [0u8; DHCP_BUFFER];
        loop {
            let len = match dhcp.recv_from(&mut incoming).await {
                Ok((len, _)) => len,
                Err(err) => {
                    error!("apheap: dhcp receive: {err:?}");
                    continue;
                }
            };
            let request = match Packet::decode(&incoming[..len]) {
                Ok(request) => request,
                Err(err) => {
                    error!("apheap: dhcp decode: {err:?}");
                    continue;
                }
            };
            let mut option_buf = Options::buf();
            let Some(reply) = leases.handle_request(&mut option_buf, &options, &request) else {
                continue;
            };
            let bytes = match reply.encode(&mut outgoing) {
                Ok(bytes) => bytes,
                Err(err) => {
                    error!("apheap: dhcp encode: {err:?}");
                    continue;
                }
            };
            // No relay on this network; a client without an address only hears a broadcast.
            let to = if !request.ciaddr.is_unspecified() && !request.broadcast {
                request.ciaddr
            } else {
                Ipv4Addr::BROADCAST
            };
            match dhcp.send_to(bytes, (to, 68)).await {
                Ok(()) => info!(
                    "apheap: dhcp reply {} bytes to {to}, offered {}, peak {}",
                    bytes.len(),
                    reply.yiaddr,
                    esp_alloc::HEAP.stats().max_usage
                ),
                Err(err) => error!("apheap: dhcp send: {err:?}"),
            }
        }
    };

    let watching = async {
        let mut last = esp_alloc::HEAP.used();
        loop {
            match embassy_futures::select::select(
                wifi.wait_for_access_point_connected_event_async(),
                Timer::after(TICK),
            )
            .await
            {
                embassy_futures::select::Either::First(event) => {
                    info!("apheap: station event {event:?}");
                    // The same wait also returns when a station leaves.
                    if !matches!(event, Ok(AccessPointStationEventInfo::Connected(_))) {
                        stage("7 client left", &mut last);
                        continue;
                    }
                    stage("7 client joined", &mut last);
                    let end = Instant::now() + WATCH;
                    while Instant::now() < end {
                        Timer::after(TICK).await;
                        stage("7 watching", &mut last);
                    }
                    stage("7 after watch", &mut last);
                }
                embassy_futures::select::Either::Second(()) => stage("waiting", &mut last),
            }
        }
    };

    join4(
        async {
            if let Err(err) = runner.run().await {
                error!("apheap: ble runner: {err:?}");
            }
        },
        net.run(),
        serving,
        join(watching, dhcp_serving),
    )
    .await;
    teetotum::step::halt()
}

fn now_secs() -> u64 {
    Instant::now().as_secs()
}

enum Path {
    Root,
    Blob,
}

/// Reads the request head and tells which of the two pages it asks for.
async fn request_path(socket: &mut TcpSocket<'_>) -> Option<Path> {
    let mut head = [0u8; 512];
    let mut len = 0;
    while len < head.len() {
        match socket.read(&mut head[len..]).await {
            Ok(0) | Err(_) => break,
            Ok(n) => len += n,
        }
        if head[..len].windows(4).any(|w| w == b"\r\n\r\n") {
            break;
        }
    }
    let head = &head[..len];
    if head.starts_with(b"GET / ") {
        Some(Path::Root)
    } else if head.starts_with(b"GET /blob ") {
        Some(Path::Blob)
    } else {
        None
    }
}

/// Sends a response: `body` as it is, or `generated` bytes of a counting pattern when it is
/// empty. Returns the bytes of body that went out.
async fn respond(
    socket: &mut TcpSocket<'_>,
    kind: &str,
    body: &[u8],
    generated: usize,
) -> usize {
    let length = if body.is_empty() { generated } else { body.len() };
    let head = format!(
        "HTTP/1.1 200 OK\r\nContent-Type: {kind}\r\nContent-Length: {length}\r\nConnection: close\r\n\r\n"
    );
    if write_all(socket, head.as_bytes()).await.is_err() {
        return 0;
    }
    if !body.is_empty() {
        return if write_all(socket, body).await.is_ok() { body.len() } else { 0 };
    }
    let mut chunk = [0u8; CHUNK];
    let mut sent = 0;
    while sent < generated {
        let n = (generated - sent).min(chunk.len());
        for (i, b) in chunk[..n].iter_mut().enumerate() {
            *b = (sent + i) as u8;
        }
        if write_all(socket, &chunk[..n]).await.is_err() {
            break;
        }
        sent += n;
    }
    sent
}

async fn write_all(socket: &mut TcpSocket<'_>, mut bytes: &[u8]) -> Result<(), ()> {
    while !bytes.is_empty() {
        match socket.write(bytes).await {
            Ok(0) | Err(_) => return Err(()),
            Ok(n) => bytes = &bytes[n..],
        }
    }
    Ok(())
}
